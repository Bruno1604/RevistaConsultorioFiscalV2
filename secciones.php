  function cf_sec_id($str) {
      $str = mb_strtolower($str, 'UTF-8');
      $str = strtr($str, [
          'á'=>'a', 'é'=>'e', 'í'=>'i', 'ó'=>'o', 'ú'=>'u', 'ñ'=>'n',
          'Á'=>'a', 'É'=>'e', 'Í'=>'i', 'Ó'=>'o', 'Ú'=>'u', 'Ñ'=>'n'
      ]);
      $str = preg_replace('/[^a-z0-9]+/u', '-', $str);
      return trim($str, '-');
  }

