<script>
(function () {
  const itemsPorPagina = 6;
  const botones = document.querySelectorAll('.cuadros__nav-btn');
  const fichas  = document.querySelectorAll('.ficha');
  const filtro  = document.getElementById('seccionFiltro');
  const vacio   = document.getElementById('seccionVacio');

  function mostrar(id) {
    fichas.forEach((f) => f.classList.toggle('on', f.id === 'ficha-' + id));
    botones.forEach((b) => b.classList.toggle('on', b.dataset.target === id));
    if (window.innerWidth < 1000) {
      const panel = document.getElementById('seccionPanel');
      if (panel) window.scrollTo({ top: panel.offsetTop - 100, behavior: 'smooth' });
    }
  }

  function paginarSeccion(ficha) {
    const lista = ficha.querySelector('.articulos-lista');
    const pager = ficha.querySelector('.articulo-pager');
    if (!lista || !pager) return;

    const articulos = Array.from(lista.querySelectorAll('.articulo-item'));
    const totalPaginas = Math.max(1, Math.ceil(articulos.length / itemsPorPagina));
    if (articulos.length <= itemsPorPagina) {
      articulos.forEach((item) => item.classList.add('is-visible'));
      pager.classList.add('hidden');
      return;
    }

    let paginaActual = 1;

    function render() {
      const inicio = (paginaActual - 1) * itemsPorPagina;
      const fin = inicio + itemsPorPagina;

      articulos.forEach((item, index) => {
        item.classList.toggle('is-visible', index >= inicio && index < fin);
      });

      const paginas = Array.from({ length: totalPaginas }, (_, i) => i + 1);
      const inicioLabel = inicio + 1;
      const finLabel = Math.min(fin, articulos.length);

      const btns = paginas.map((num) => {
        const selected = num === paginaActual ? 'is-current' : '';
        return `<button type="button" class="articulo-page-btn ${selected}" data-page="${num}" aria-label="Ir a la página ${num}">${num}</button>`;
      }).join('');

      pager.innerHTML = `
        <div class="articulo-pager__nav">
          <button type="button" data-dir="prev" ${paginaActual === 1 ? 'disabled' : ''}>Anterior</button>
        </div>
        <span class="articulo-pager__status">Mostrando ${inicioLabel}-${finLabel} de ${articulos.length}</span>
        <div class="articulo-pager__nav">${btns}</div>
        <div class="articulo-pager__nav">
          <button type="button" data-dir="next" ${paginaActual === totalPaginas ? 'disabled' : ''}>Siguiente</button>
        </div>
      `;

      pager.classList.remove('hidden');

      pager.querySelectorAll('[data-page]').forEach((btn) => {
        btn.addEventListener('click', () => {
          paginaActual = Number(btn.dataset.page);
          render();
        });
      });

      pager.querySelectorAll('[data-dir]').forEach((btn) => {
        btn.addEventListener('click', () => {
          const dir = btn.dataset.dir === 'prev' ? -1 : 1;
          const next = paginaActual + dir;
          if (next >= 1 && next <= totalPaginas) {
            paginaActual = next;
            render();
          }
        });
      });
    }

    render();
  }

  fichas.forEach((ficha) => paginarSeccion(ficha));

  botones.forEach((b) => b.addEventListener('click', () => mostrar(b.dataset.target)));

  // Índice plegable en móvil
  const toggle = document.getElementById('seccionToggle');
  const cuerpo = document.getElementById('seccionCuerpo');
  if (toggle && cuerpo) {
    toggle.addEventListener('click', () => {
      const abierto = cuerpo.classList.toggle('open');
      toggle.setAttribute('aria-expanded', abierto);
    });
    // Al elegir una sección, el índice se cierra solo en móvil
    botones.forEach((b) => b.addEventListener('click', () => {
      if (window.innerWidth < 1000) {
        cuerpo.classList.remove('open');
        toggle.setAttribute('aria-expanded', 'false');
      }
    }));
  }

  // Filtro del índice
  if (filtro) {
    filtro.addEventListener('input', () => {
      const q = filtro.value.trim().toLowerCase();
      let hay = 0;
      botones.forEach((b) => {
        const ok = !q || b.textContent.toLowerCase().indexOf(q) !== -1;
        b.parentElement.hidden = !ok;
        if (ok) { hay++; }
      });
      if (vacio) vacio.hidden = hay > 0;
    });
  }
})();
</script>

